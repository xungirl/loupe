"""Summarise results/bench/*.jsonl into results/bench/summary.md (mean ± sample stdev over repetitions)."""
import json
import re
import statistics as S
from collections import defaultdict
from pathlib import Path

B = Path(__file__).resolve().parents[1] / "results" / "bench"


def ms(xs):
    m = S.mean(xs)
    sd = S.stdev(xs) if len(xs) > 1 else 0.0
    return m, sd, min(xs), max(xs)


def fmt(xs, d=0):
    m, sd, lo, hi = ms(xs)
    return f"{m:,.{d}f} ± {sd:,.{d}f} (min {lo:,.{d}f}, max {hi:,.{d}f}, n={len(xs)})"


out = ["# Benchmark summary (generated by scripts/bench_summary.py)", "", (B / "machine.txt").read_text().strip(), ""]

out += ["## Ingest throughput (8 concurrent clients, fresh DB per run)", "",
        "| batch (spans/request) | spans sent | committed spans/s | accepted spans/s | 429s | request p50 ms | request p99 ms |",
        "|---|---|---|---|---|---|---|"]
groups = defaultdict(list)
for line in open(B / "ingest.jsonl"):
    r = json.loads(line)
    groups[r["batch"]].append(r)
for batch in sorted(groups):
    rs = groups[batch]
    assert all(r["written_on_server"] == r["accepted_spans"] for r in rs)
    out.append(f"| {batch} | {rs[0]['spans']:,} | {fmt([r['committed_spans_per_sec'] for r in rs])} | "
               f"{fmt([r['accepted_spans_per_sec'] for r in rs])} | {fmt([r['rejected_429'] for r in rs])} | "
               f"{fmt([r['request_p50_ms'] for r in rs], 2)} | {fmt([r['request_p99_ms'] for r in rs], 2)} |")
single = S.mean(r["committed_spans_per_sec"] for r in groups[1])
best = max(S.mean(r["committed_spans_per_sec"] for r in groups[b]) for b in groups if b > 1)
out += ["", f"Batched (best mean) / per-span committed throughput: **{best / single:.2f}x**.", ""]

out += ["## Overload (queue 5,000 spans, 32 clients, no retries, 600 requests × 500 spans)", "",
        "| rep | requests | 429 | accepted spans | written by server | max queue depth seen | request p99 ms | max RSS |",
        "|---|---|---|---|---|---|---|---|"]
rss = dict(re.findall(r"(rep\d) max_rss_kb=\s*(\d+)", (B / "overload_rss.txt").read_text()))
for line in open(B / "overload.jsonl"):
    r = json.loads(line)
    rep = r["label"].split()[0]
    out.append(f"| {rep} | {r['requests']} | {r['rejected_429']} | {r['accepted_spans']:,} | {r['written_on_server']:,} | "
               f"{r['max_queue_depth_observed']:,.0f} | {r['request_p99_ms']:.1f} | {int(rss.get(rep, 0)) / 1024:.1f} MB |")
out.append("")

rows = [json.loads(l) for l in open(B / "query.jsonl")]
eps = defaultdict(list)
for r in rows:
    for e in r["results"]:
        eps[e["endpoint"]].append(e)
out += [f"## Query latency at {rows[0]['spans']:,} spans / {rows[0]['traces']:,} traces (3 server runs)", "",
        rows[0]["measured"], "", "| endpoint | requests/run | p50 ms | p95 ms | p99 ms |", "|---|---|---|---|---|"]
for k, v in eps.items():
    out.append(f"| {k} | {v[0]['n']} | {fmt([e['p50_ms'] for e in v], 2)} | {fmt([e['p95_ms'] for e in v], 2)} | {fmt([e['p99_ms'] for e in v], 2)} |")
out += ["", "Generation: " + (B / "query_generate.txt").read_text().strip(),
        "Detectors over the whole DB: " + " ".join((B / "query_detect_all.txt").read_text().split()), ""]

imp = defaultdict(list)
for line in open(B / "import.jsonl"):
    r = json.loads(line)
    imp[r["dry"]].append(r)
r0 = imp[False][0]
out += ["## Claude Code importer (synthetic transcripts)", "", (B / "import_corpus.txt").read_text().strip(), "",
        "| mode | seconds | MB/s | lines/s | spans/s |", "|---|---|---|---|---|"]
for dry, label in ((True, "parse + convert only"), (False, "parse + convert + write SQLite")):
    rs = imp[dry]
    out.append(f"| {label} | {fmt([r['seconds'] for r in rs], 3)} | {fmt([r['bytes'] / 1e6 / r['seconds'] for r in rs], 1)} | "
               f"{fmt([r['lines'] / r['seconds'] for r in rs])} | {fmt([r['spans'] / r['seconds'] for r in rs])} |")
out += ["", f"Corpus: {r0['files']} files, {r0['lines']:,} lines, {r0['bytes'] / 1e6:.1f} MB → {r0['spans']:,} spans.", ""]

gb = re.findall(r"BenchmarkBuild10k-\d+\s+\d+\s+(\d+) ns/op\s+(\d+) B/op\s+(\d+) allocs/op", (B / "assembly_gobench.txt").read_text())
out += ["## In-process assembly (go test -bench, 10,000-span trace)", "",
        f"ns/op: {fmt([float(g[0]) for g in gb])}; {int(gb[0][1]) / 1e6:.1f} MB and {gb[0][2]} allocations per build.", ""]
(B / "summary.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
